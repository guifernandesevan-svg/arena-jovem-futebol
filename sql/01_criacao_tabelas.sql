CREATE TABLE responsavel (
    id_responsavel INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome VARCHAR(100),
    cpf VARCHAR(14),
    data_nascimento DATE,
    rua VARCHAR(100),
    numero VARCHAR(10),
    bairro VARCHAR(60),
    cep VARCHAR(9)
);


CREATE TABLE professor (
    id_professor INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome VARCHAR(100),
    cpf VARCHAR(14),
    data_nascimento DATE,
    salario NUMERIC(10,2),
    data_contratacao DATE
);


CREATE TABLE turma (
    id_turma INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    categoria VARCHAR(50),
    horario TIME,
    capacidade INT,
    id_professor INT UNIQUE NOT NULL,
    FOREIGN KEY (id_professor) REFERENCES professor(id_professor)
);


CREATE TABLE aluno (
    id_aluno INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome VARCHAR(100),
    data_nascimento DATE,
    rua VARCHAR(100),
    numero VARCHAR(10),
    bairro VARCHAR(60),
    cep VARCHAR(9),
    data_cadastro DATE,
    id_responsavel INT NOT NULL,
    FOREIGN KEY (id_responsavel) REFERENCES responsavel(id_responsavel)
);


CREATE TABLE matricula (
    id_matricula INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    data_matricula DATE,
    status VARCHAR(30),
    id_aluno INT NOT NULL,
    id_turma INT NOT NULL,
    FOREIGN KEY (id_aluno) REFERENCES aluno(id_aluno),
    FOREIGN KEY (id_turma) REFERENCES turma(id_turma)
);


CREATE TABLE telefone_responsavel (
    id_telefone INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    telefone VARCHAR(20) NOT NULL,
    id_responsavel INT NOT NULL,
    FOREIGN KEY (id_responsavel) REFERENCES responsavel(id_responsavel)
);
